import assert from "node:assert/strict";
import { readdir } from "node:fs/promises";
import { DatabaseSync } from "node:sqlite";

const baseURL = process.env.BASE_URL ?? "http://localhost:3000";
if (!["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("This fixture test is restricted to a local development server.");
const call = async (path, method = "GET", body) => {
  const response = await fetch(`${baseURL}${path}`, { method, headers: body ? { "Content-Type": "application/json" } : {}, body: body ? JSON.stringify(body) : undefined });
  return { status: response.status, body: await response.json() };
};
assert.equal((await call("/api/bootstrap")).status, 200);
assert.equal((await call("/api/memory")).status, 200);
const directory = ".wrangler/state/v3/d1/miniflare-D1DatabaseObject";
const files = (await readdir(directory)).filter((name) => name.endsWith(".sqlite") && name !== "metadata.sqlite");
assert.equal(files.length, 1, "select the intended local database explicitly if there are multiple D1 files");
const db = new DatabaseSync(`${directory}/${files[0]}`);
db.exec("PRAGMA busy_timeout=5000");
const suffix = crypto.randomUUID().replaceAll("-", "").slice(0, 8);
const ownEvent = `QA_E_${suffix}`, ownTask = `QA_T_${suffix}`, foreignEvent = `QA_FE_${suffix}`, foreignTask = `QA_FT_${suffix}`, foreignAuth = `QA_FA_${suffix}`, foreignNotice = `QA_FN_${suffix}`;
const ownAuth = `QA_A_${suffix}`, ownNotice = `QA_N_${suffix}`;
const foreignDevice = `QA_FD_${suffix}`, protectedDevice = `QA_PD_${suffix}`, lightingDevice = `QA_LD_${suffix}`;
const timestamp = new Date().toISOString();
const foreignFamily = `QA_F_${suffix}`;
const eventInsert = db.prepare("INSERT INTO events (id, family_id, title, description, risk_level, status, source, created_at, updated_at) VALUES (?, ?, ?, '', 'critical', 'pending_confirmation', 'qa_fixture', ?, ?)");
const taskInsert = db.prepare("INSERT INTO tasks (id, family_id, title, assignee, creator, source_event_id, status, due_at) VALUES (?, ?, ?, 'M003', 'QA fixture', ?, 'in_progress', ?)");
let createdTaskId;
try {
  eventInsert.run(ownEvent, "F001", "QA fixture: record verification", timestamp, timestamp);
  eventInsert.run(foreignEvent, foreignFamily, "QA fixture: another family", timestamp, timestamp);
  taskInsert.run(ownTask, "F001", "QA fixture: verify a result", ownEvent, timestamp);
  taskInsert.run(foreignTask, foreignFamily, "QA fixture: private task", foreignEvent, timestamp);
  db.prepare("INSERT INTO authorizations (id, family_id, action, resource, created_at) VALUES (?, ?, 'QA fixture', 'QA fixture', ?)").run(foreignAuth, foreignFamily, timestamp);
  db.prepare("INSERT INTO notifications (id, family_id, category, title, detail, time, read) VALUES (?, ?, 'system', 'QA fixture', '', ?, 0)").run(foreignNotice, foreignFamily, timestamp);
  db.prepare("INSERT INTO devices (id, family_id, name, kind) VALUES (?, ?, 'QA private device', 'lighting')").run(foreignDevice, foreignFamily);
  db.prepare("INSERT INTO devices (id, family_id, name, kind) VALUES (?, 'F001', 'QA protected device', 'lock')").run(protectedDevice);
  db.prepare("INSERT INTO devices (id, family_id, name, kind) VALUES (?, 'F001', 'QA lighting device', 'lighting')").run(lightingDevice);
  db.prepare("INSERT INTO family_memories (family_id, member, type, content, source, importance) VALUES (?, 'QA private member', 'event', ?, 'QA fixture', 3)").run(foreignFamily, `private-${suffix}`);
  db.prepare("INSERT INTO tool_runs (family_id, tool, status, input_json, output_json) VALUES (?, 'QA private tool', 'success', '{}', '{}')").run(foreignFamily);
  assert.equal((await call(`/api/devices/${foreignDevice}/actions`, "POST", { action: "light_on", confirmed: true })).status, 404);
  assert.equal((await call("/api/smart-home", "POST", { action: "light_on", entityId: foreignDevice, confirmed: true })).status, 404);
  assert.equal((await call("/api/tools", "POST", { tool: "control_device", input: { action: "light_on", entityId: foreignDevice, confirmed: true } })).status, 404);
  assert.equal((await call(`/api/devices/${protectedDevice}/actions`, "POST", { action: "unlock", confirmed: true })).status, 403);
  assert.equal((await call("/api/smart-home", "POST", { action: "light_on", entityId: lightingDevice })).status, 403);
  assert.equal((await call("/api/tools", "POST", { tool: "unknown_tool" })).status, 400);
  const memories = await call("/api/memory");
  assert.ok(!memories.body.memories.some((memory) => memory.content === `private-${suffix}`));
  const runs = await call("/api/tools");
  assert.ok(!runs.body.runs.some((run) => run.tool === "QA private tool"));
  assert.equal((await call("/api/settings", "PUT", { settings: { privacy_camera: "off" } })).status, 400);
  assert.equal((await call("/api/agent", "POST", { query: 123 })).status, 400);
  assert.equal((await call(`/api/tasks/${foreignTask}`)).status, 404);
  assert.equal((await call(`/api/events/${foreignEvent}`)).status, 404);
  assert.equal((await call(`/api/tasks/${foreignTask}`, "PATCH", { status: "in_progress" })).status, 404);
  assert.equal((await call(`/api/events/${foreignEvent}`, "PATCH", { title: "must not change" })).status, 404);
  assert.equal((await call(`/api/authorizations/${foreignAuth}`, "PATCH", { policy: "always_deny" })).status, 404);
  await call(`/api/notifications/${foreignNotice}/read`, "POST");
  assert.equal(db.prepare("SELECT read FROM notifications WHERE id=?").get(foreignNotice).read, 0);
  assert.equal(db.prepare("SELECT title FROM events WHERE id=?").get(foreignEvent).title, "QA fixture: another family");
  assert.equal((await call(`/api/events/${ownEvent}`, "PATCH", { riskLevel: "normal" })).status, 400);
  assert.equal((await call(`/api/events/${ownEvent}`, "PATCH", { status: "resolved" })).status, 400);
  assert.equal((await call(`/api/events/${ownEvent}`, "PATCH", { status: "closed" })).status, 409);
  assert.equal((await call(`/api/tasks/${ownTask}`, "PATCH", { status: "invalid" })).status, 400);
  assert.equal((await call(`/api/tasks/${ownTask}`, "PATCH", { status: "completed" })).status, 409);
  assert.equal((await call(`/api/tasks/${ownTask}`, "PATCH", { status: "completed", evidence: "unsaved record" })).status, 409);
  assert.equal((await call("/api/tasks", "POST", { title: "QA fixture", assignee: "FOREIGN_MEMBER" })).status, 400);
  assert.equal((await call("/api/tasks", "POST", { title: "QA fixture", assignee: "M003", sourceEventId: foreignEvent })).status, 404);
  const createdTask = await call("/api/tasks", "POST", { title: "QA fixture: associated task", assignee: "M003", sourceEventId: ownEvent, priority: "high" });
  assert.equal(createdTask.status, 201);
  createdTaskId = createdTask.body.id;
  assert.ok((await call(`/api/events/${ownEvent}`)).body.relatedTasks.includes(createdTaskId));
  assert.equal((await call(`/api/tasks/${createdTaskId}`, "PATCH", { evidence: "QA fixture: verified the associated task." })).status, 200);
  const racingWrites = await Promise.all([call(`/api/tasks/${createdTaskId}`, "PATCH", { status: "completed", version: 1 }), call(`/api/tasks/${createdTaskId}`, "PATCH", { evidence: "QA fixture: concurrent edit", version: 1 })]);
  assert.deepEqual(racingWrites.map((result) => result.status).sort(), [200, 409], "completion and an edit from the same old version cannot both save");
  const afterRace = (await call(`/api/tasks/${createdTaskId}`)).body;
  if (afterRace.status === "completed") assert.equal(afterRace.evidence, "QA fixture: verified the associated task.");
  else assert.equal((await call(`/api/tasks/${createdTaskId}`, "PATCH", { status: "completed", version: afterRace.version })).status, 200);
  assert.notEqual((await call(`/api/events/${ownEvent}`)).body.status, "resolved", "the remaining task still needs confirmation");
  const record = await call(`/api/tasks/${ownTask}`, "PATCH", { evidence: "QA fixture: contacted the person and verified the result." });
  assert.equal(record.status, 200);
  assert.equal(record.body.status, "waiting_confirmation");
  assert.equal((await call(`/api/tasks/${ownTask}`, "PATCH", { evidence: "outdated draft", version: 0 })).status, 409);
  const attempts = await Promise.all([call(`/api/tasks/${ownTask}`, "PATCH", { status: "completed", familyConfirmedAt: "1900-01-01T00:00:00Z" }), call(`/api/tasks/${ownTask}`, "PATCH", { status: "completed" })]);
  assert.deepEqual(attempts.map((result) => result.status).sort(), [200, 409], "simultaneous confirmations must save exactly once");
  const complete = attempts.find((result) => result.status === 200);
  assert.equal(complete.status, 200);
  assert.equal(complete.body.status, "completed");
  assert.notEqual(complete.body.familyConfirmedAt, "1900-01-01T00:00:00Z");
  const event = await call(`/api/events/${ownEvent}`);
  assert.equal(event.body.status, "resolved");
  assert.equal(event.body.timeline.at(-1).title, "任务完成已回传");
  assert.equal((await call(`/api/tasks/${ownTask}`, "PATCH", { status: "completed" })).status, 409);
  assert.equal(db.prepare("SELECT count(*) AS count FROM audit_logs WHERE target=?").get(ownTask).count, 2);
  db.prepare("INSERT INTO authorizations (id, family_id, action, resource, created_at, event_id, status) VALUES (?, 'F001', 'QA decision', 'QA protected resource', ?, ?, 'pending')").run(ownAuth, timestamp, ownEvent);
  db.prepare("INSERT INTO notifications (id, family_id, category, title, detail, time, read, event_id) VALUES (?, 'F001', 'action', 'QA decision', '', ?, 0, ?)").run(ownNotice, timestamp, ownEvent);
  const decisions = await Promise.all([call(`/api/authorizations/${ownAuth}/decisions`, "POST", { decision: "reject" }), call(`/api/authorizations/${ownAuth}/decisions`, "POST", { decision: "approve" })]);
  assert.deepEqual(decisions.map((result) => result.status).sort(), [200, 409]);
  assert.equal(db.prepare("SELECT count(*) AS count FROM audit_logs WHERE id=?").get(`ALAD:${ownAuth}`).count, 1);
  assert.equal(db.prepare("SELECT read FROM notifications WHERE id=?").get(ownNotice).read, 1);
  assert.equal((await call(`/api/events/${ownEvent}`)).body.timeline.filter((entry) => entry.id === `LAD:${ownAuth}`).length, 1);
  console.log("Local API integrity verified: family isolation across records/memory/tools/devices, protected operations, evidence gating, server timestamps, atomic persistence. Fixtures removed.");
} finally {
  for (const id of [ownTask, foreignTask, createdTaskId].filter(Boolean)) { db.prepare("DELETE FROM tasks WHERE id=?").run(id); db.prepare("DELETE FROM audit_logs WHERE target=?").run(id); }
  for (const id of [ownEvent, foreignEvent]) db.prepare("DELETE FROM events WHERE id=?").run(id);
  db.prepare("DELETE FROM authorizations WHERE id=?").run(foreignAuth);
  db.prepare("DELETE FROM notifications WHERE id=?").run(foreignNotice);
  db.prepare("DELETE FROM audit_logs WHERE target=?").run(ownTask);
  for (const id of [foreignDevice, protectedDevice, lightingDevice]) { db.prepare("DELETE FROM devices WHERE id=?").run(id); db.prepare("DELETE FROM audit_logs WHERE target=?").run(id); }
  db.prepare("DELETE FROM family_memories WHERE family_id=?").run(foreignFamily);
  db.prepare("DELETE FROM tool_runs WHERE family_id=?").run(foreignFamily);
  db.prepare("DELETE FROM authorizations WHERE id=?").run(ownAuth);
  db.prepare("DELETE FROM notifications WHERE id=?").run(ownNotice);
  db.prepare("DELETE FROM audit_logs WHERE id=?").run(`ALAD:${ownAuth}`);
  db.close();
}
