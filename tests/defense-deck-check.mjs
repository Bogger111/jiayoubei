import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { chromium } from "playwright-core";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "test-results/defense-deck");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const errors = [], remoteRequests = [], observations = [];
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/^https?:/.test(request.url())) remoteRequests.push(request.url()); });
  await page.goto(pathToFileURL(resolve(root, "家有备-中期答辩.html")).href);
  await page.evaluate(() => Promise.all([...document.images].map(img => img.decode())));
  assert.equal(await page.locator(".slide").count(), 19);
  const totalSeconds = await page.locator(".slide").evaluateAll(slides => slides.reduce((n, slide) => n + Number(slide.dataset.seconds), 0));
  for (let i = 0; i < 19; i++) {
    await page.evaluate(i => { location.hash = "slide-" + (i + 1); }, i);
    await page.waitForFunction(i => document.querySelector(".slide.active") === document.querySelectorAll(".slide")[i], i);
    const geometry = await page.locator(".slide.active").evaluate(slide => {
      const bounds = slide.getBoundingClientRect();
      const outside = [...slide.querySelectorAll("h1,h2,h3,p,li,td,th,img,.slide-foot,.cover-bottom")].filter(node => {
        if (node.closest(".speaker-note")) return false;
        const rect = node.getBoundingClientRect();
        return rect.width && rect.height && (rect.left < bounds.left - 1 || rect.right > bounds.right + 1 || rect.top < bounds.top - 1 || rect.bottom > bounds.bottom + 1);
      }).map(node => ({ tag: node.tagName, text: node.textContent.slice(0, 80), class: node.className }));
      const foot = slide.querySelector(".slide-foot");
      const body = slide.querySelector(".slide-body");
      return { title: slide.dataset.title, outside, bodyOverlapsFooter: Boolean(foot && body && body.getBoundingClientRect().bottom > foot.getBoundingClientRect().top + 1) };
    });
    observations.push(geometry);
    await page.screenshot({ path: resolve(output, String(i + 1).padStart(2, "0") + ".png") });
  }
  await page.keyboard.press("Home");
  assert.equal(await page.locator(".slide.active").getAttribute("data-title"), "家有备");
  await page.keyboard.press("ArrowRight");
  assert.equal(await page.locator("#pageLabel").innerText(), "02 / 19");
  await page.keyboard.press("f");
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await page.keyboard.press("f");
  await page.waitForFunction(() => !document.fullscreenElement);
  await page.keyboard.press("n");
  assert.equal(await page.locator("#notesPanel").isVisible(), true);
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("#notesPanel").isVisible(), false);
  await page.keyboard.press("o");
  const directory = page.getByRole("dialog", { name: "演示目录" });
  await directory.getByRole("button", { name: /本机视觉检测/ }).click();
  assert.equal(await page.locator("#pageLabel").innerText(), "11 / 19");
  await page.keyboard.press("b");
  assert.equal(await page.locator("#blackout").isVisible(), true);
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("#blackout").isVisible(), false);
  await page.keyboard.press("e");
  await page.locator('input[name="hours"]').fill("20");
  await page.locator('input[name="expense"]').fill("100");
  await page.locator('input[name="feedback"]').fill("10");
  await page.locator('input[name="scenarioTests"]').fill("4");
  await page.getByRole("button", { name: "保存并应用", exact: true }).click();
  assert.equal(await page.locator('[data-derived="feedbackEfficiency"]').textContent(), "5.0 条 / 10 小时");
  assert.equal(await page.locator('[data-derived="testEfficiency"]').textContent(), "4.0 次 / 100 元");
  await page.locator('input[name="hours"]').fill("0");
  await page.getByRole("button", { name: "保存并应用", exact: true }).click();
  assert.equal(await page.locator('[data-derived="feedbackEfficiency"]').textContent(), "待补数据");
  await page.locator('input[name="team"]').fill("<script>1</script>");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出填写后的 HTML", exact: true }).click();
  const download = await downloadPromise;
  assert.equal(await download.failure(), null);
  const exported = resolve(output, "edited.html");
  await download.saveAs(exported);
  assert.ok((await readFile(exported, "utf8")).includes("\\u003cscript>1\\u003c/script>"));
  const isolated = await browser.newContext();
  const exportPage = await isolated.newPage();
  exportPage.on("pageerror", error => errors.push(error.message));
  await exportPage.goto(pathToFileURL(exported).href);
  assert.equal(await exportPage.locator('[data-field="team"]').textContent(), "<script>1</script>");
  assert.equal(await exportPage.locator("script").count(), 2);
  await isolated.close();
  await page.getByRole("button", { name: "恢复默认资料", exact: true }).click();
  await page.locator('#editor [data-close]').click();
  await page.reload();
  assert.equal(await page.locator('[data-derived="feedbackEfficiency"]').textContent(), "待补数据");
  await page.getByRole("button", { name: "阅读", exact: true }).click();
  await page.emulateMedia({ media: "print" });
  const printed = await page.locator(".slide").evaluateAll(slides => slides.map(slide => ({ display: getComputedStyle(slide).display, height: slide.getBoundingClientRect().height })));
  assert.ok(printed.every(slide => slide.display === "flex" && slide.height === 900));
  await page.pdf({ path: resolve(output, "print-check.pdf"), width: "1600px", height: "900px", printBackground: true, preferCSSPageSize: true });
  const pdf = (await readFile(resolve(output, "print-check.pdf"))).toString("latin1");
  assert.equal((pdf.match(/\/Type\s*\/Page\b/g) ?? []).length, 19);
  await page.emulateMedia({ media: "screen" });
  const phone = await context.newPage();
  await phone.setViewportSize({ width: 390, height: 844 });
  phone.on("pageerror", error => errors.push(error.message));
  await phone.goto(pathToFileURL(resolve(root, "家有备-中期答辩.html")).href);
  assert.equal(await phone.locator("body").evaluate(body => body.classList.contains("reading")), true);
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  const readingLayout = await phone.locator(".slide").evaluateAll(slides => slides.map(slide => {
    const bound = slide.getBoundingClientRect();
    const foot = slide.querySelector(".slide-foot");
    const images = [...slide.querySelectorAll(".screen img")];
    return { title: slide.dataset.title, imageIssues: images.filter(img => {
      const r = img.getBoundingClientRect();
      return r.height < 80 || r.top < bound.top || foot && r.bottom > foot.getBoundingClientRect().top;
    }).map(img => img.alt) };
  }));
  assert.ok(readingLayout.every(slide => !slide.imageIssues.length), JSON.stringify(readingLayout));
  await phone.screenshot({ path: resolve(output, "phone.png") });
  await phone.getByRole("button", { name: "目录", exact: true }).click();
  await phone.locator("#directoryList button").last().click();
  await phone.screenshot({ path: resolve(output, "phone-end.png") });
  assert.equal(await phone.locator("#pageLabel").innerText(), "19 / 19");
  await phone.getByRole("button", { name: "目录", exact: true }).click();
  await phone.getByRole("button", { name: "填写真实资料", exact: true }).click();
  await phone.getByRole("dialog", { name: "填写真实资料" }).waitFor();
  await phone.locator('#editor [data-close]').click();
  await phone.locator('.slide[data-title="本机视觉检测"]').scrollIntoViewIfNeeded();
  await phone.waitForFunction(() => document.getElementById("pageLabel").textContent === "11 / 19");
  await phone.screenshot({ path: resolve(output, "phone-vision.png") });
  await phone.getByRole("button", { name: "目录", exact: true }).click();
  await phone.locator("#directoryList button").last().click();
  await phone.getByRole("button", { name: "阅读", exact: true }).click();
  assert.equal(await phone.locator(".slide.active").getAttribute("data-title"), "现场演示与问答");
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await writeFile(resolve(output, "observations.json"), JSON.stringify({ totalSeconds, observations, errors, remoteRequests }, null, 2));
  assert.deepEqual(remoteRequests, [], "standalone deck should not fetch network resources");
  assert.deepEqual(errors, []);
  assert.ok(observations.every(slide => !slide.outside.length && !slide.bodyOverlapsFooter), JSON.stringify(observations.filter(slide => slide.outside.length || slide.bodyOverlapsFooter)));
  console.log(JSON.stringify({ slides: 19, totalSeconds, offline: true, keyboard: true, forms: true, export: true, phone: true, print: true, observations: resolve(output, "observations.json") }));
} finally {
  await browser.close();
}
